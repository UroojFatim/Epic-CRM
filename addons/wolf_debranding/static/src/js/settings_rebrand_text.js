/** @odoo-module **/
// Robust rebrand in Settings (handles highlights & inputs)

(function () {
    const FROM = /Odoo/gi;
    const TO = "WolfOfArchesCRM";

    const PHRASE_REPLACERS = [
        { re: /\bMy\s+Odoo(?:\.com)?\s+account\b/gi, to: "My WolfOfArchesCRM account" },
        { re: /\bOdoo\s+IAP\b/gi, to: "WolfOfArchesCRM IAP" },
        { re: /\bOdoo\s+IAP\s*\(In-App Purchases\)/gi, to: "WolfOfArchesCRM IAP (In-App Purchases)" },
        { re: /\bAPI Keys allow your users to access Odoo\b/gi, to: "API Keys allow your users to access WolfOfArchesCRM" },
        { re: /\bInstall the Odoo Progressive Web App\b/gi, to: "Install the WolfOfArchesCRM Progressive Web App" },
        { re: /\bwhen Odoo is installed through the browser\b/gi, to: "when WolfOfArchesCRM is installed through the browser" },
        { re: /\bThis file is automatically generated by Odoo\b/gi, to: "This file is automatically generated by WolfOfArchesCRM" },
    ];

    function replaceString(s) {
        if (!s) return s;
        PHRASE_REPLACERS.forEach(({ re, to }) => { s = s.replace(re, to); });
        return s.replace(FROM, TO);
    }

    function skip(el) {
        const a = el.closest?.("a");
        return !!(a && /odoo\.(com|sh|saas)/i.test(a.href || ""));
    }

    function textNode(n) {
        const t = n.nodeValue;
        if (t && /Odoo/i.test(t)) n.nodeValue = replaceString(t);
    }

    function elementNode(el) {
        if (skip(el)) return;

        // Highlights created by Settings search (mark/span fragments)
        el.querySelectorAll("mark, span, em, strong, b, i, .o_searchable_highlight, .o_search_value").forEach(s => {
            if (/^\s*Odoo\s*$/i.test(s.textContent || "")) s.textContent = TO;
        });

        // Inputs / Textareas
        if (el.matches("input, textarea")) {
            if (typeof el.value === "string" && /Odoo/i.test(el.value)) el.value = replaceString(el.value);
            const ph = el.getAttribute("placeholder");
            if (ph && /Odoo/i.test(ph)) el.setAttribute("placeholder", replaceString(ph));
        }

        // Simple text containers (safety net)
        const SIMPLE = "label, small, p, span, div.o_setting_right_pane, div.text-muted";
        el.querySelectorAll(SIMPLE).forEach(node => {
            if (skip(node)) return;
            if (/Odoo/i.test(node.textContent || "")) node.innerHTML = replaceString(node.innerHTML);
        });
    }

    function run(root) {
        const scope = root.querySelector(".o_settings_container, .o_web_settings, .o_form_view") || root;
        if (!scope) return;

        const walker = document.createTreeWalker(scope, NodeFilter.SHOW_TEXT, {
            acceptNode(n){ return /Odoo/i.test(n.nodeValue || "") ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_REJECT; }
        });
        const nodes = [];
        while (walker.nextNode()) nodes.push(walker.currentNode);
        nodes.forEach(textNode);

        scope.querySelectorAll("*:not(script):not(style)").forEach(elementNode);
    }

    function start() {
        run(document);
        const MO = window.MutationObserver || window.WebKitMutationObserver;
        if (!MO) return;
        const obs = new MO(muts => {
            for (const m of muts) for (const n of m.addedNodes) if (n && n.nodeType === 1) run(n);
        });
        obs.observe(document.body || document.documentElement, { childList: true, subtree: true });
    }

    if (document.readyState === "loading") {
        document.addEventListener("DOMContentLoaded", start, { once: true });
    } else {
        start();
    }
})();
